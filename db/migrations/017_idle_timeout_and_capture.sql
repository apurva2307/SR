-- Inactivity sign-out the department can tune, and a record of attempts to
-- capture a page on screen.
--
-- The idle limit moves from an environment variable to a setting so an
-- administrator can change it without a deploy. Default 15 minutes.

INSERT INTO settings (key, value) VALUES ('session.idle_minutes', '15'::jsonb)
ON CONFLICT (key) DO NOTHING;

-- Last time each session was used, by user: what "online now" is read from.
CREATE INDEX IF NOT EXISTS sessions_user_seen_idx
  ON sessions (user_id, last_seen_at DESC) WHERE revoked_at IS NULL;

